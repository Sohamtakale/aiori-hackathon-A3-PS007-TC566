#!/usr/bin/env bash
# Build the Mayfly lab (FR-E1). Re-running it rebuilds the lab from scratch.
#
#   sw        : bridge br0 + one veth port per node (v<node>); IPv6 off here
#   router    : eth0 = fe80::1, fd4d:6179:666c:1::1/64; runs radvd
#   d1..d5    : SLAAC devices (Tenant A: d1-d3, Tenant B: d4-d5)
#   attacker  : unenrolled on-link node
#
# Safety: only namespaces are created. Nothing is added to, or changed in,
# the host network namespace, and no namespace has a link to the outside.
set -euo pipefail
. "$(dirname "$0")/lib.sh"

require_root
command -v ip >/dev/null || die "iproute2 not found"
[[ -n "$RADVD" && -x "$RADVD" ]] || die "radvd not found: sudo dnf install radvd"

# ---------------------------------------------------------------- preflight
if [[ -f $STATE_DIR/namespaces ]]; then
    log "existing lab found, tearing it down first"
    "$LAB_DIR/down.sh"
fi
for ns in $(all_namespaces); do
    ns_exists "$ns" && die "namespace '$ns' already exists and was not created by this lab; refusing to touch it"
done

mkdir -p "$STATE_DIR"
created=()
lab_ok=0
cleanup_on_failure() {
    (( lab_ok )) && return
    warn "setup failed; removing what was created"
    "$LAB_DIR/down.sh" || true
}
trap cleanup_on_failure EXIT

new_ns() {
    ip netns add "$1"
    created+=("$1")
    printf '%s\n' "${created[@]}" > "$STATE_DIR/namespaces"
    ip -n "$1" link set lo up
}

# ---------------------------------------------------------------- switch
log "creating switch namespace '$SW_NS' with bridge $BRIDGE"
new_ns "$SW_NS"
# The switch is pure L2: no IPv6 on any of its interfaces, so it adds no ND noise.
nssysctl "$SW_NS" net.ipv6.conf.all.disable_ipv6=1 net.ipv6.conf.default.disable_ipv6=1
ip -n "$SW_NS" link add "$BRIDGE" type bridge stp_state 0 forward_delay 0 mcast_snooping 0
ip -n "$SW_NS" link set "$BRIDGE" up

attach() {   # attach() <node>: veth v<node> (switch) <-> eth0 (node)
    local node=$1 port
    port=$(port_for "$node")
    ip -n "$SW_NS" link add "$port" type veth peer name eth0 netns "$node"
    ip -n "$SW_NS" link set "$port" master "$BRIDGE" up
    ip -n "$node" link set eth0 address "$(mac_for "$node")"
}

# ---------------------------------------------------------------- router
log "creating router namespace '$ROUTER_NS'"
new_ns "$ROUTER_NS"
attach "$ROUTER_NS"
nssysctl "$ROUTER_NS" net.ipv6.conf.all.forwarding=1 net.ipv6.conf.eth0.accept_ra=0
# Fixed link-local so the monitor's rule R2 has a stable router address.
ip -n "$ROUTER_NS" link set eth0 addrgenmode none
ip -n "$ROUTER_NS" link set eth0 up
ip -n "$ROUTER_NS" addr add "$ROUTER_LL/64" dev eth0 nodad
ip -n "$ROUTER_NS" addr add "$ROUTER_ADDR/64" dev eth0 nodad

log "starting radvd in '$ROUTER_NS' (prefix $LAB_PREFIX)"
mkdir -p "$RADVD_DIR"
umask 022
cat > "$RADVD_CONF" <<EOF
# Generated by lab/up.sh - Mayfly lab only.
interface eth0 {
    AdvSendAdvert on;
    MinRtrAdvInterval $RA_MIN_INTERVAL;
    MaxRtrAdvInterval $RA_MAX_INTERVAL;
    AdvDefaultLifetime $RA_ROUTER_LIFETIME;
    AdvDefaultPreference medium;
    prefix $LAB_PREFIX {
        AdvOnLink on;
        AdvAutonomous on;
        AdvValidLifetime 3600;
        AdvPreferredLifetime 1800;
    };
};
EOF
chmod 644 "$RADVD_CONF"
if command -v selinuxenabled >/dev/null && selinuxenabled; then
    # Give the files the policy's radvd_var_run_t label so the confined radvd can use them.
    restorecon -R "$RADVD_DIR" 2>/dev/null || warn "restorecon on $RADVD_DIR failed"
fi
nsx "$ROUTER_NS" "$RADVD" -c -C "$RADVD_CONF" >/dev/null 2>&1 || die "radvd rejected $RADVD_CONF"
nsx "$ROUTER_NS" "$RADVD" -C "$RADVD_CONF" -p "$RADVD_PID" -m logfile -l "$RADVD_LOG"
for _ in $(seq 20); do [[ -s $RADVD_PID ]] && break; sleep 0.25; done
[[ -s $RADVD_PID ]] || die "radvd did not start; see $RADVD_LOG (SELinux: ausearch -m avc -ts recent)"

# ---------------------------------------------------------------- devices + attacker
setup_host() {   # SLAAC node, random IIDs (no MAC-derived EUI-64), no kernel temp addrs yet
    local node=$1
    new_ns "$node"
    attach "$node"
    nssysctl "$node" net.ipv6.conf.all.forwarding=0 \
        net.ipv6.conf.eth0.accept_ra=1 net.ipv6.conf.eth0.autoconf=1 \
        net.ipv6.conf.eth0.use_tempaddr=0
    ip -n "$node" link set eth0 addrgenmode random
    ip -n "$node" link set eth0 up
}
for d in $DEVICES; do
    log "creating device namespace '$d'"
    setup_host "$d"
done
log "creating attacker namespace '$ATTACKER_NS'"
setup_host "$ATTACKER_NS"

lab_ok=1

# ---------------------------------------------------------------- wait for SLAAC
log "waiting for SLAAC addresses"
deadline=$((SECONDS + 30))
for node in $DEVICES $ATTACKER_NS; do
    until ip -n "$node" -6 -o addr show dev eth0 scope global -tentative | grep -q .; do
        (( SECONDS < deadline )) || { warn "$node got no global address (check $RADVD_LOG)"; break; }
        sleep 0.5
    done
done

echo
printf '%-9s %-11s %-18s %s\n' NODE PORT MAC "GLOBAL ADDRESS"
for node in $(all_nodes); do
    addr=$(ip -n "$node" -6 -o addr show dev eth0 scope global | awk '{print $4}' | paste -sd, -)
    printf '%-9s %-11s %-18s %s\n' "$node" "$(port_for "$node")" "$(mac_for "$node")" "${addr:--}"
done
echo
log "lab is up. Verify with: sudo lab/check.sh   Tear down with: sudo lab/down.sh"
